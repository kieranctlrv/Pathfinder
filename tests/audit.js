/* Systems audit: every stat that parts and perks produce, and whether anything reads it.
   node tests/audit.js            prints the report
   node tests/audit.js --write    also writes design/systems-audit.md
   A key counts as read when its quoted name appears in engine or screen code outside run-data.js
   (prefix families like ceil.<channel> count when their prefix is read). */
const fs = require('fs'), path = require('path');
const D = require('../src/run/run-data.js'), RM = require('../src/run/run-map.js');
const root = path.join(__dirname, '..', 'src');
const files = []; (function walk(d) { fs.readdirSync(d).forEach(f => { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (/\.js$/.test(f) && !/run-data\.js$/.test(f) && !/legacy/.test(p)) files.push(p); }); })(root);
const code = files.map(f => fs.readFileSync(f, 'utf8')).join('\n');
const read = k => code.indexOf("'" + k + "'") >= 0 || code.indexOf('"' + k + '"') >= 0 || [/^ceil\./, /^order\.uses\./, /^thr:/, /^role\./].some(re => re.test(k) && code.indexOf("'" + k.match(re)[0]) >= 0);
const prod = {};   // key -> [where]
const add = (k, where) => (prod[k] = prod[k] || []).push(where);
const unwired = [], textOnly = [];
D.PARTS.forEach(p => {
  (p.base || []).forEach(e => { if (e.k === 's') add(e.key, p.name + ' (base)'); });
  if (p.thr) (p.thr.fx || []).forEach(e => add(e.key, p.name + ' (threshold)'));
  (p.perks || []).forEach(k => {
    if (k.d) unwired.push(p.name + ' L' + k.l + ': ' + k.n);
    else if (!k.e.length) textOnly.push(p.name + ' L' + k.l + ': ' + k.n);
    k.e.forEach(e => { if (e.k === 's') add(e.key, p.name + ' L' + k.l + ' ' + k.n); });
  });
});
const TAGS = ['w.energy', 'w.kind'];   /* descriptive tags, not effects */
const keys = Object.keys(prod).sort(), dead = keys.filter(k => !read(k) && TAGS.indexOf(k) < 0);
const roles = Object.keys(RM.ROLE), noRole = D.PARTS.filter(p => !RM.ROLE[p.id]).map(p => p.name + ' (' + p.slot + ')');
const perks = RM.OPERK.map(p => p.d + ' L' + p.l + ': ' + p.t);
const L = [];
L.push('# Systems audit', '', 'Generated by `node tests/audit.js --write`. Re-run after any change to parts, perks or engine stats.', '');
L.push('## Totals', '', '- Parts: ' + D.PARTS.length + ', stat keys produced: ' + keys.length + ', read by code: ' + (keys.length - dead.length) + ', dead: ' + dead.length,
  '- Perks authored but not wired (d:1): ' + unwired.length + '; perks with no effect at all: ' + textOnly.length,
  '- Parts with a scan or time role: ' + roles.length + ' of ' + D.PARTS.length + '; officer perks: ' + perks.length, '');
L.push('## Dead stats (produced, never read)', '');
dead.forEach(k => L.push('- `' + k + '` from ' + prod[k].join('; ')));
if (!dead.length) L.push('- none');
L.push('', '## Perks not wired yet', ''); unwired.forEach(t => L.push('- ' + t)); if (!unwired.length) L.push('- none');
L.push('', '## Perks with no effect listed', ''); textOnly.forEach(t => L.push('- ' + t)); if (!textOnly.length) L.push('- none');
L.push('', '## Parts with no scan or time role', ''); noRole.forEach(t => L.push('- ' + t));
L.push('', '## Every stat and who produces it', ''); keys.forEach(k => L.push('- `' + k + '`' + (dead.indexOf(k) >= 0 ? ' **DEAD**' : '') + ': ' + prod[k].join('; ')));
const out = L.join('\n') + '\n';
if (process.argv.indexOf('--write') >= 0) fs.writeFileSync(path.join(__dirname, '..', 'design', 'systems-audit.md'), out);
console.log(out.split('\n## Every stat')[0]);
